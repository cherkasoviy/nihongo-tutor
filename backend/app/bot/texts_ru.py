def streak_word(n: int) -> str:
    """«день / дня / дней» — русская форма множественного числа."""
    if 11 <= n % 100 <= 14:
        return "дней"
    match n % 10:
        case 1:
            return "день"
        case 2 | 3 | 4:
            return "дня"
        case _:
            return "дней"


